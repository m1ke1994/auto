assert.ok(production.includes('vodopyanov_site:'))
assert.ok(production.includes('c62cbd5295425d14b53bb17ccd3642a363b1383e'))
assert.ok(production.includes('condition: service_healthy'))
assert.ok(ssl.includes('docker/nginx/templates-https:/etc/nginx/templates:ro'))
assert.ok(!ssl.includes('acme-challenge:/var/www/acme'))
assert.ok(acme.includes('stariy-site.ru'))
assert.ok(acme.includes('/.well-known/acme-challenge/'))
assert.ok(acme.includes('root /etc/nginx/templates;'))
assert.ok(https.includes('/etc/letsencrypt/live/stariy-site.ru/fullchain.pem'))
assert.ok(https.includes('vodopyanov_site:3000'))
assert.ok(register.includes('vodopyanov_cms_register "$MODE"'))
assert.ok(register.includes('--check'))
assert.ok(register.includes('scripts/lib/vodopyanov-cms.sh'))
assert.ok(register.includes('flock -w 30 9'))
