import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const read = path => readFileSync(resolve(root, path), 'utf8')
const production = read('ydro/docker-compose.prod.yml')
const ssl = read('ydro/docker-compose.https.yml')
const acme = read('ydro/docker/nginx/templates-https/stariy-site-acme.conf.template')
const https = read('ydro/docker/nginx/templates-https/stariy-site-https.conf.template.example')
const register = read('scripts/register-vodopyanov-site.sh')
const deploy = read('scripts/deploy-vodopyanov-site.sh')
const activate = read('scripts/activate-vodopyanov-https.sh')
assert.ok(production.includes('vodopyanov_site:'))
assert.ok(production.includes('b1c4fd7020ed9a2ea531da5d5f80a3db3fb2c66b'))
assert.ok(production.includes('condition: service_healthy'))
assert.ok(ssl.includes('docker/nginx/acme-challenge:/var/www/acme:ro'))
assert.ok(acme.includes('stariy-site.ru'))
assert.ok(acme.includes('/.well-known/acme-challenge/'))
assert.ok(https.includes('/etc/letsencrypt/live/stariy-site.ru/fullchain.pem'))
assert.ok(https.includes('vodopyanov_site:3000'))
assert.ok(register.includes('DRY RUN'))
assert.ok(register.includes('Site.objects.create('))
assert.ok(register.includes('get_or_create_client_for_site'))
assert.ok(register.includes('Existing site has a different domain or owner'))
assert.ok(deploy.includes('pg_dump'))
assert.ok(deploy.includes('pg_restore --list'))
assert.ok(deploy.includes('dc build vodopyanov_site'))
assert.ok(deploy.includes('dc up -d --no-deps nginx'))
assert.ok(!/\b(dc down|migrate|flush|reset_demo_data)\b/.test(deploy))
assert.ok(activate.includes('sudo test -s /etc/letsencrypt/live/stariy-site.ru/fullchain.pem'))
assert.ok(activate.includes('nginx -t'))
console.log('Vodopyanov TrackNode integration configuration checks passed')
