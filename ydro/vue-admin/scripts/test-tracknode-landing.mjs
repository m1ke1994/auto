import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'

const root = process.cwd()
const landing = fs.readFileSync(path.join(root, 'src/views/LandingPage.vue'), 'utf8')
const router = fs.readFileSync(path.join(root, 'src/router/index.js'), 'utf8')
const sitemap = fs.readFileSync(path.join(root, 'public/sitemap.xml'), 'utf8')

assert.match(landing, /Заказать сайт/)
assert.match(landing, /Подключить TrackNode/)
assert.match(landing, /Посмотреть возможности/)
assert.match(landing, /Обсудим ваш проект/)
assert.match(landing, /https:\/\/tishechkinalexandr\.ru\//)
assert.match(landing, /rel="noopener noreferrer"/)
assert.match(landing, /portfolio_link_click/)
assert.match(landing, /tracknode_landing_contact/)
assert.match(landing, /v-model="form\.consent"/)
assert.match(landing, /RouterLink to="\/privacy"/)
assert.match(landing, /RouterLink to="\/terms"/)
assert.match(landing, /FAQPage/)
assert.match(landing, /Organization/)
assert.match(landing, /WebSite/)
assert.match(landing, /Service/)
assert.match(landing, /href="#features"/)
assert.match(landing, /href="#website"/)
assert.match(landing, /href="#analytics"/)
assert.match(landing, /href="#leads"/)
assert.match(landing, /href="#seo"/)
assert.match(landing, /href="#pricing"/)
assert.match(landing, /href="#contact"/)

assert.doesNotMatch(landing, /id="projects"/)
assert.doesNotMatch(landing, /href="#projects"/)
assert.doesNotMatch(landing, /project-grid/)
assert.doesNotMatch(landing, /Примеры проектов|Наши проекты|Проекты/)

assert.match(router, /path: '\/terms'/)
assert.match(router, /path: '\/privacy'/)
assert.match(router, /path: '\/user-agreement'[\s\S]*redirect: '\/terms'/)
assert.match(sitemap, /https:\/\/tracknode\.ru\/terms/)
assert.match(sitemap, /https:\/\/tracknode\.ru\/privacy/)
assert.doesNotMatch(sitemap, /projects/)

console.log('TrackNode landing regression checks passed')
